        dir_dat_out = os.path.join(dir_root, '04_statistics', '01_continuous', '01_results', '02_omc_to_mmc_error_per_s_dynamic')
        dir_dat_in = os.path.join(dir_root, '03_data', 'preprocessed_data', '03_fully_preprocessed_dynamic')

